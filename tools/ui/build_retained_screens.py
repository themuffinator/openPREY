# -------------------------------------------------------------- typed values

def length(value: float, unit: str = "dp") -> dict:
    return {"type": "length", "value": round(value, 3), "unit": unit}

def ul(value: float) -> dict:
    """A length given in stock units."""
    return length(value * U)

def colour(value: list[float]) -> dict:
    return {"type": "color", "value": value}

def keyword(value: str) -> dict:
    return {"type": "keyword", "value": value}

def number(value: float) -> dict:
    return {"type": "number", "value": value}

def font(name: str) -> dict:
    return {"type": "font", "value": name}

def text(key: str) -> dict:
    return {"type": "text", "value": key}

def image(source: str) -> dict:
    return {"type": "image", "value": source}

def transform(tx: float = 0, ty: float = 0, sx: float = 1, sy: float = 1) -> dict:
    """A translation in stock units with a scale."""
    return {"type": "transform", "unit": "dp", "value": [round(tx * U, 3), round(ty * U, 3), sx, sy, 0]}


def absolute(left=None, top=None, width=None, height=None, right=None, bottom=None) -> dict:
    """Absolute placement in stock units; a dict passes through as a typed value."""
    props = {"position": keyword("absolute")}
    for name, value in (("left", left), ("top", top), ("width", width), ("height", height),
                        ("right", right), ("bottom", bottom)):
        if value is None:
            continue
        props[name] = value if isinstance(value, dict) else ul(value)
    return props

FULL = {"position": keyword("absolute"), "left": length(0), "top": length(0),
        "width": length(100, "%"), "height": length(100, "%")}
PASSIVE = {"pointer-events": keyword("none")}
# The stock 4:3 canvas centred on the screen: the classic backdrop expands
# its canvas about the centre on both axes (section 3), so a stage pinned to
# the top would part from the wordmark and the Sphere on a screen taller than 4:3.
STAGE = {"position": keyword("absolute"), "left": length(50, "%"), "top": length(50, "%"),
         "margin-left": length(-CANVAS_W * U / 2), "margin-top": length(-CANVAS_H * U / 2),
         "width": ul(CANVAS_W), "height": ul(CANVAS_H)}


# ------------------------------------------------------------------ geometry

_TOKEN = re.compile(r"[MLHVCQZ]|-?\d*\.?\d+(?:e-?\d+)?")


def svg(ident: str, d: str, *, scale=(U, U), offset=(0.0, 0.0), fill=None, stroke=None, blend=None) -> dict:
    """A path from absolute SVG path data (M L H V C Q Z), the form the
    Interface Atlas draws its furniture in. Coordinates are scaled and then
    offset, so data in stock units arrives in dp."""
    tokens = _TOKEN.findall(d)
    commands, index, pen, op = [], 0, (0.0, 0.0), ""

    def take() -> float:
        nonlocal index
        value = float(tokens[index])
        index += 1
        return value

    def out(x: float, y: float) -> list:
        return [round(x * scale[0] + offset[0], 3), round(y * scale[1] + offset[1], 3)]

    def add(kind: str, points: list) -> None:
        commands.append({"id": f"p{len(commands)}", "op": kind, "points": points})

    while index < len(tokens):
        if tokens[index].isalpha():
            op = tokens[index]
            index += 1
            if op == "Z":
                commands.append({"id": f"p{len(commands)}", "op": "close"})
                continue
        if op == "M":
            pen = (take(), take())
            add("move", [out(*pen)])
            op = "L"                        # further pairs after a move are lines
        elif op == "L":
            pen = (take(), take())
            add("line", [out(*pen)])
        elif op == "H":
            pen = (take(), pen[1])
            add("line", [out(*pen)])
        elif op == "V":
            pen = (pen[0], take())
            add("line", [out(*pen)])
        elif op == "C":
            c1, c2, pen = (take(), take()), (take(), take()), (take(), take())
            add("cubic", [out(*c1), out(*c2), out(*pen)])
        elif op == "Q":
            c1, pen = (take(), take()), (take(), take())
            add("quadratic", [out(*c1), out(*pen)])
        else:
            raise ValueError(f"{ident}: unsupported path data {d!r}")
    result = {"id": ident, "commands": commands}
    if fill is not None:
        result["fill"] = fill
    if stroke is not None:
        result["stroke"] = stroke
    if blend:
        result["blend"] = blend
    return result


def ellipse_d(cx: float, cy: float, rx: float, ry: float) -> str:
    """An ellipse as four cubic arcs: the path model has no arc command."""
    k = 0.5522847498
    return (f"M{cx - rx} {cy}C{cx - rx} {cy - k * ry} {cx - k * rx} {cy - ry} {cx} {cy - ry}"
            f"C{cx + k * rx} {cy - ry} {cx + rx} {cy - k * ry} {cx + rx} {cy}"
            f"C{cx + rx} {cy + k * ry} {cx + k * rx} {cy + ry} {cx} {cy + ry}"
            f"C{cx - k * rx} {cy + ry} {cx - rx} {cy + k * ry} {cx - rx} {cy}Z")


def solid(value: list[float]) -> dict:
    return {"type": "solid", "color": colour(value)}

def linear(start, end, stops) -> dict:
    return {"type": "linear", "from": list(start), "to": list(end),
            "stops": [{"at": at, "color": colour(value)} for at, value in stops]}

def radial(centre, edge, stops) -> dict:
    return {"type": "radial", "from": list(centre), "to": list(edge),
            "stops": [{"at": at, "color": colour(value)} for at, value in stops]}

def stroke(paint: dict, width: float, *, minimum: float = 1, join: str = "miter", cap: str = "butt") -> dict:
    """A stroke whose width is given in dp."""
    return {"paint": paint, "widthDp": round(width, 3), "minimumPixels": minimum, "join": join, "cap": cap}


# --------------------------------------------------------------------- nodes

def group(ident: str, props: dict, children=(), **extra) -> dict:
    node = {"id": ident, "type": "group", "properties": props}
    if children:
        node["children"] = list(children)
    node.update(extra)
    return node

def vector(ident: str, props: dict, paths: list | None = None, *, symbol: str | None = None, **extra) -> dict:
    node = {"id": ident, "type": "vector", "properties": props}
    if symbol:
        node["symbol"] = symbol
    else:
        node["paths"] = paths or []
    node.update(extra)
    return node

def picture(ident: str, source: str, props: dict, fit: str = "fill") -> dict:
    return {"id": ident, "type": "image", "properties": {"image": image(source), "image-fit": keyword(fit), **props}}


def label(ident: str, key: str, box, face: str, scale: float, tint: list[float], *, align: str = "center",
          shadow: bool = False, wrap: bool = False, ty: float = 0.0, centre: bool = False, **more) -> list[dict]:
    """A text window: `box` is its stock rect, `scale` its textscale and `ty`
    its textaligny. The first line's capitals land where the stock window
    draws them (CAP_STOCK, CAP_LINE): one line is centred in a box of the
    window's height, moved to suit; wrapped text runs on 1.2 em lines from
    there. With `centre` the capitals sit in the middle of the box's height
    instead, for rows and fields the stock draws with its own widgets. With
    `shadow` the engine's drop shadow is drawn as a black copy 1 u down and
    across, under the label. Returns the nodes back to front."""
    x, y, w, h = box
    em = EM * scale
    line = em * 1.2 if wrap else h
    if centre:
        y -= CAP_LINE[face] * em
    else:
        y = y + ty + (CAP_STOCK[face] - CAP_LINE[face]) * em - line / 2
    if align == "left":
        x += TEXT_INSET
    props = {
        **absolute(x, y, w, h),
        "font-family": font(face), "font-size": length(em * U * FONT_FIT),
        "line-height": ul(line),
        "text-align": keyword(align), "white-space": keyword("normal" if wrap else "nowrap"),
        **PASSIVE, **more,
    }
    nodes = []
    if shadow:
        under = dict(props)
        under.update(absolute(x + 1, y + 1, w, h))
        nodes.append({"id": f"{ident}-shadow", "type": "text",
                      "properties": {"text": text(key), **under, "color": colour(SHADOW)}})
    nodes.append({"id": ident, "type": "text", "properties": {"text": text(key), **props, "color": colour(tint)}})
    return nodes


def poly(ident: str, points: list, *, fill=None, stroke=None, closed: bool = True) -> dict:
    """A straight-edged path. Each coordinate is in dp, or a
    {"fraction", "dp"} pair measured on the node's box, so the shape follows
    a node that changes size."""
    commands = [{"id": f"p{index}", "op": "move" if index == 0 else "line", "points": [[x, y]]}
                for index, (x, y) in enumerate(points)]
    if closed:
        commands.append({"id": "close", "op": "close"})
    result = {"id": ident, "commands": commands}
    if fill is not None:
        result["fill"] = fill
    if stroke is not None:
        result["stroke"] = stroke
    return result


def far(dp: float = 0.0) -> dict:
    """A coordinate measured back from the node's far edge."""
    return {"fraction": 1, "dp": round(-dp, 3)}


# ----------------------------------------------------------------- timelines

def track(node: str, prop: str, keys: list) -> dict:
    """keys: (ms, typed value[, easing of the interval starting here])."""
    result = []
    for key in keys:
        entry = {"atMs": key[0], "value": key[1]}
        if len(key) > 2 and key[2] is not None:
            entry["easing"] = key[2]
        result.append(entry)
    return {"node": node, "property": prop, "keys": result}


class Document:
    def __init__(self, ident: str):
        self.ident = ident
        self.state: dict = {}
        self.actions: dict = {}
        self.events: dict = {}
        self.bindings: list = []
        self.symbols: dict = {}
        self.timelines: list = []
        self.key_rows: list = []      # each binding row's binding, in row order (bind_row)

    def bind(self, node: str, prop: str, value) -> None:
        self.bindings.append({"id": f"{node}.{prop}", "node": node, "property": prop, "value": value})

    def session(self, command: str) -> str:
        """A session verb as an action of the same name
        (SessionMenuCommand in src/ui/UserInterfaceRetained.cpp)."""
        self.actions[command] = {"operation": "session.menu", "arguments": {"command": command}}
        return command

    def timeline(self, ident: str, duration: int, tracks: list, *, complete: str | None = None,
                 iterations: int | None = None, essential: bool | None = None) -> str:
        """`iterations` 0 repeats until cancelled; `essential` keeps the
        authored timing under reduced motion, for motion that is the content."""
        item = {"id": ident, "durationMs": duration, "tracks": tracks}
        if iterations is not None:
            item["iterations"] = iterations
        if essential is not None:
            item["essential"] = essential
        if complete:
            item["complete"] = complete
        self.timelines.append(item)
        return ident

    def states(self, control: str, tracks: dict, *, enter: int = HOVER_IN_MS, leave: int = HOVER_OUT_MS) -> dict:
        """A control's five feedback timelines. `tracks` maps a state to
        [(node, property, typed value)]; every state covers the same
        properties. Hover and focus arrive over `enter` and rest returns over
        `leave`, both linear as the stock transitions are (section 8). An
        entry may add a fourth item, the milliseconds that part alone takes
        in every state, for a part that fades while the rest changes at once."""
        durations = {"default": leave, "hover": enter, "focus": enter, "pressed": 60, "disabled": leave}
        ids = {}
        for state, duration in durations.items():
            ident = f"{control}.{state}"
            items, longest = [], duration
            for node, prop, value, *own in tracks[state]:
                took = own[0] if own else duration
                longest = max(longest, took)
                items.append(track(node, prop, [(0, value), (took, value)]))
            self.timeline(ident, longest, items)
            ids[state] = ident
        return ids

    def build(self, root: dict) -> dict:
        result = {"format": "retained-ui", "version": 1, "id": self.ident,
                  "canvas": {"height": 720, "minWidth": 960}}
        for key in ("state", "actions", "events", "bindings", "symbols"):
            if getattr(self, key):
                result[key] = getattr(self, key)
        result["timelines"] = self.timelines
        result["root"] = root
        return result


def control(key: str, ids: dict, *, action: str | None = None, event: str | None = None, **more) -> dict:
    result = {"role": "button", "label": key, "states": ids}
    if action:
        result["action"] = action
    else:
        result["event"] = event
    result.update(more)
    return result


# ----------------------------------------------------------------- furniture
# Section 6 and Appendix B, as the Interface Atlas constructs them.

CLAW_D = ("M47 0H128V7.5C116 9.5 103 14.5 93 18.5C89 42 84 74 71.5 106C64 115 36 117 17 104.5"
          "C6 96 1 79 2 60C3 42 10 28 19 19C28 10 37 3.5 47 0Z")
CLAW_W, CLAW_H = 38, 32                       # drawn size of the 128x128-texel corner
CLAW_SCALE = (CLAW_W * U / 128, CLAW_H * U / 128)


def claw_symbol(doc: Document) -> str:
    """The claw corner (window_cornerUL): a slate body, its dark oval socket
    and the pale rim, 7 texels wide inside the silhouette. The rim is a
    14-texel stroke that each corner's mask cuts to the body."""
    if "claw" not in doc.symbols:
        sx, sy = CLAW_SCALE
        doc.symbols["claw"] = [
            svg("body", CLAW_D, scale=CLAW_SCALE, fill=linear([0, 0], [CLAW_W * U, CLAW_H * U], [
                (0, rgb("#576272")), (0.55, rgb("#3B4351")), (1, rgb("#2E3541"))])),
            svg("socket", ellipse_d(43.5, 66.5, 16.5, 21.5), scale=CLAW_SCALE,
                fill=radial([43.5 * sx, 66.5 * sy], [43.5 * sx, 88 * sy], [
                    (0, rgb("#14171B")), (0.72, rgb("#171B20")), (1, rgb("#363E4A"))])),
            svg("rim", CLAW_D, scale=CLAW_SCALE, stroke=stroke(solid(RAIL), 14 * (sx + sy) / 2, join="round")),
        ]
    return "claw"


def claw(doc: Document, ident: str, corner: str) -> dict:
    """One corner of a frame: "ul", "ur", "ll" or "lr", mirrored into place."""
    props = absolute(width=CLAW_W, height=CLAW_H,
                     left=0 if corner[1] == "l" else None, right=0 if corner[1] == "r" else None,
                     top=0 if corner[0] == "u" else None, bottom=0 if corner[0] == "l" else None)
    props["transform"] = transform(sx=1 if corner[1] == "l" else -1, sy=1 if corner[0] == "u" else -1)
    props.update(PASSIVE)
    return vector(ident, props, symbol=claw_symbol(doc), mask={"paths": [
        svg("body", CLAW_D, scale=CLAW_SCALE, fill=solid([1, 1, 1, 1]))]})


def frame_parts(doc: Document, ident: str, alpha: float, inset: float, *, upper: bool = True,
                ends: float = 25) -> list[dict]:
    """The claw-cornered frame (superWindowDef) as parts that follow their
    parent's box: a black body `ends` u inside each end (25 on every frame
    but the death screen's) and `inset` u below the top, a 1.53 u rail along
    the top and the foot between the corners, and the four claws. There are
    no side rails. `upper` is false for a frame no taller than its corners,
    which draws only the lower pair and the foot rail; a growing frame keeps
    its upper parts in "<ident>-upper" so that a timeline can bring them in."""
    rail = colour(RAIL)
    parts = [
        group(f"{ident}-body", {**absolute(left=ends, right=ends, top=inset, bottom=0),
                                "background-color": colour([0, 0, 0, alpha]), **PASSIVE}),
        group(f"{ident}-rail-foot", {**absolute(left=CLAW_W, right=CLAW_W, bottom=0, height=1.53),
                                     "background-color": rail, **PASSIVE}),
        claw(doc, f"{ident}-claw-ll", "ll"),
        claw(doc, f"{ident}-claw-lr", "lr"),
    ]
    if upper:
        parts.append(group(f"{ident}-upper", {**FULL, "opacity": number(1), **PASSIVE}, [
            group(f"{ident}-rail-top", {**absolute(left=CLAW_W, right=CLAW_W, top=0, height=1.53),
                                        "background-color": rail, **PASSIVE}),
            claw(doc, f"{ident}-claw-ul", "ul"),
            claw(doc, f"{ident}-claw-ur", "ur"),
        ]))
    return parts


def title_bar(ident: str, box, *, inverted: bool = False) -> dict:
    """A frame title bar: wider at the top, or at the foot when `inverted`
    (the bottom title bar), so the pair frames the panel like a lens."""
    x, y, w, h = box
    d = f"M5 0H{w - 5}L{w - .5} {h}H.5Z" if inverted else f"M.75 0H{w - .75}L{w - 7.5} {h}H7.5Z"
    return vector(ident, {**absolute(x, y, w, h), **PASSIVE}, [svg("plate", d, fill=solid(PLATE_TITLE))])


def button_d(w: float, h: float) -> str:
    """The 3-slice button's outline: a curved slope at its leading end, wider
    at the foot, and a slanted chamfer at its trailing end (edgeWidth 12)."""
    e, t, b = 12, h * .06, h * .95
    return (f"M{e * .95} {t}H{w - e * .9}L{w - e * .3} {h * .5}L{w - e * .23} {b}H{e * .3}"
            f"Q{e * .14} {b} {e * .18} {h * .8}L{e * .28} {h * .5}Q{e * .36} {t} {e * .95} {t}Z")


def button(doc: Document, ident: str, key: str, box, *, action: str | None = None, event: str | None = None,
           scale: float = 0.33, enabled=None, extra=(), extra_tracks: dict | None = None, **more) -> dict:
    """A 3-slice button (section 6): the graded plate at rest, the even
    rollover plate and a white label under the pointer or focus, and for
    focus the outline at full prey.rail as well, so it stays visible when the
    pointer rests elsewhere (section 7). `extra` are further parts in the
    button's subtree and `extra_tracks` their feedback, for content a button
    reveals while it is lit."""
    x, y, w, h = box
    d = button_d(w, h)
    edge = stroke(solid(rgb(PLATE_BUTTON)), 1.2 * U, join="round")
    size = {**absolute(0, 0, w, h), **PASSIVE}
    plate = vector(f"{ident}-plate", {**size, "opacity": number(1)}, [svg("plate", d, fill=linear(
        [0, 0], [w * U, 0], [(0, rgb(PLATE_BUTTON, 0.77)), (1, rgb(PLATE_BUTTON, 0.06))]), stroke=edge)])
    hot = vector(f"{ident}-hot", {**size, "opacity": number(0)}, [
        svg("plate", d, fill=solid(rgb(PLATE_BUTTON, 0.30)), stroke=edge)])
    rim = vector(f"{ident}-rim", {**size, "opacity": number(0)}, [
        svg("rim", d, stroke=stroke(solid(RAIL), 1.5 * U, join="round"))])
    text_nodes = label(f"{ident}-label", key, (0, 0, w, h), BODY, scale, TEXT_BUTTON, shadow=True, ty=1)

    def lit(plate_on: float, hot_on: float, rim_on: float, tint: list[float]) -> list:
        return [(f"{ident}-plate", "opacity", number(plate_on)), (f"{ident}-hot", "opacity", number(hot_on)),
                (f"{ident}-rim", "opacity", number(rim_on)), (f"{ident}-label", "color", colour(tint))]
    tracks = {
        "default": lit(1, 0, 0, TEXT_BUTTON),
        "hover": lit(0, 1, 0, TEXT_HOVER),
        "focus": lit(0, 1, 1, TEXT_HOVER),
        "pressed": lit(0, 1, 0, TEXT_HOVER),
        "disabled": lit(1, 0, 0, TEXT_BUTTON_OFF),
    }
    for state, items in (extra_tracks or {}).items():
        tracks[state] = tracks[state] + items
    # The stock button swaps its plate at once; only the navigation slides.
    ids = doc.states(ident, tracks, enter=1, leave=1)
    if enabled is not None:
        doc.bind(ident, "enabled", enabled)
    return group(ident, absolute(x, y, w, h), [plate, hot, rim, *text_nodes, *extra],
                 control=control(key, ids, action=action, event=event, **more))


def link(doc: Document, ident: str, key: str, box, *, action: str | None = None, event: str | None = None,
         scale: float = 0.35, ty: float = 0.0, **more) -> dict:
    """A display-face action on a bottom bar: prey.text.bottom, brightening to
    prey.text.navHover; focus adds a hairline in prey.rail under the label."""
    x, y, w, h = box
    rim_w = min(w - 16, 110)
    rim = vector(f"{ident}-rim", {**absolute((w - rim_w) / 2, h - 3.5, rim_w, 2), "opacity": number(0), **PASSIVE}, [
        svg("rail", f"M0 1H{rim_w}", stroke=stroke(solid(RAIL), 1 * U))])
