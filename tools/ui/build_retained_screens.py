def row_setting(doc: Document, row: dict) -> dict:
    """How a stock row's setting is read and changed. Most are settings the
    engine lets a page change directly (OPTION_SETTINGS), read back from the
    CVar. The rest (OPTION_VERBS) the session acts on: the row sends a verb
    with its value, and reads either a CVar or a state the session
    publishes. Returns the control's value state, its action, the value's
    kind and what the row's stock control is overridden with."""
    cvar = row["cvar"].lower()
    if cvar in OPTION_VERBS:
        via = OPTION_VERBS[cvar]
        kind, state = via["kind"], via.get("state") or f"cv.{via['cvar']}"
        declared = {"type": kind, "initial": {"boolean": False, "number": 0}[kind]}
        if "cvar" in via:
            declared["cvar"] = via["cvar"]
        doc.state[state] = declared
        doc.actions[via["verb"]] = {"input": kind, "operation": "session.menuValue",
                                    "arguments": {"command": via["verb"], "value": {"input": "value"}}}
        return {"state": state, "action": via["verb"], "kind": kind, **via}
    name, kind = OPTION_SETTINGS[cvar]
    state, action = f"cv.{name}", f"set.{name}"
    doc.state[state] = {"type": kind, "initial": {"boolean": False, "number": 0, "string": ""}[kind], "cvar": name}
    doc.actions[action] = {"input": kind, "operation": "settings.player.set", "arguments": {"cvar": name, "value": {"input": "value"}}}
    result = {"state": state, "action": action, "kind": kind}
    if cvar in OPTION_ENABLED:
        result["enabled"] = OPTION_ENABLED[cvar]
    return result


def setting_row(doc: Document, ident: str, row: dict, origin) -> dict:
    """A setting row at its stock place (section 6): the graded plate, the
    label centred in the leading half in prey.text.label and the value in
    the trailing half in prey.text.value. A choice shows its current option
    and unfolds its list; a slider is the stock rail with its ring knob, and
    shows its number after it. A row the sound system does not offer is
    drawn at 0.40 and takes no input, as the stock page dims it."""
    x, y, w, h = row["rect"]
    setting = row_setting(doc, row)
    kind = setting["kind"]
    d = row_d(w, h)
    size = {**absolute(0, 0, w, h), **PASSIVE}
    children = [
        vector(f"{ident}-plate", dict(size), [svg("plate", d, fill=linear([0, 0], [w * U, 0], [
            (0, rgb(PLATE_ROW, 0.77)), (1, rgb(PLATE_ROW, 0.06))]), stroke=stroke(solid(rgb(PLATE_ROW)), 1 * U, join="round"))]),
        vector(f"{ident}-rim", {**size, "opacity": number(0)}, [svg("rim", d, stroke=stroke(solid(RAIL), 1.5 * U, join="round"))]),
        *label(f"{ident}-label", row["label"], row["label_rect"], BODY, 0.33, TEXT_LABEL, shadow=True, ty=row["label_ty"]),
    ]
    cx, cy, cw, ch = row["control_rect"]
    spec = {"label": row["label"], "action": setting["action"], "value": {"state": setting["state"]}}
    if row["kind"] == "choice":
        if "entries" in setting:
            entries = setting["entries"]
        else:
            count = len(row["values"]) if row["values"] else 2
            def typed(index: int):
                if kind == "boolean":
                    return (row["values"][index] != "0") if row["values"] else index == 1
                if not row["values"]:        # a yes or no on a CVar that is not a Boolean
                    return index if kind == "number" else str(index)
                if kind == "string":
                    return row["values"][index]
                number_value = float(row["values"][index])
                return int(number_value) if number_value == int(number_value) else number_value
            choices = OPTION_CHOICES.get(row["cvar"].lower(), row["choices"])
            entries = [((choices, index), typed(index)) for index in range(count)]
        # A row taller than the stock 25 u seats its value in the middle.
        value = label(f"{ident}-value", PLACEHOLDER, (cx, cy, cw, ch), BODY, 0.33, TEXT_VALUE, centre=ch > 30,
                      overflow=keyword("hidden"), **ELLIPSIS)
        # Names the session supplies (sound devices) can be long: their list
        # gives them the row's width, where a stock list sits under the value.
        named = any(isinstance(caption, dict) for caption, _ in entries)
        popup, options = choice_list(ident, entries, (0, h, w), (8, w - 16) if named else (cx, cw))
        children += [*value, popup]
        spec.update(role="choice", states=setting_states(doc, ident, f"{ident}-value"), options=options,
                    visibleRows=min(len(options), OPTION_ROWS), placementBounds="page",
                    parts={"popup": f"{ident}-popup", "viewport": f"{ident}-viewport", "content": f"{ident}-content",
                           "value": f"{ident}-value"},
                    scrollbar={"track": f"{ident}-scroll-track", "thumb": f"{ident}-scroll-thumb",
                               "lineStep": round(OPTION_H * U, 3), "minimumThumb": 24})
        if "count" in setting:
            spec["optionCount"] = setting["count"]
    else:
        low, high, step = (setting.get(key, row[key]) for key in ("low", "high", "step"))
        knob = 10 * U
        ticks = [svg("rail", f"M3 {ch / 2 - 2.5}H{cw - 3}L{cw} {ch / 2}L{cw - 3} {ch / 2 + 2.5}H3L0 {ch / 2}Z", fill=solid(SLIDER_RAIL))]
        for tick in range(0, 11):
            at = 5 + (cw - 10) * tick / 10
            ticks.append(svg(f"tick{tick}", ellipse_d(at, ch / 2, 0.9, 0.9), fill=solid(SLIDER_TICK)))
        ring = [svg("ring", ellipse_d(5, ch / 2, 4, 4), fill=solid(rgb("#05080C")), stroke=stroke(solid(SLIDER_KNOB), 1.6 * U))]
        track_node = group(f"{ident}-track", absolute(cx, cy, cw, ch), [
            vector(f"{ident}-rail", {**FULL, **PASSIVE}, ticks),
            group(f"{ident}-fill", {"position": keyword("absolute"), "left": length(0), "top": ul(ch / 2 - 1), "width": length(0),
                                    "height": ul(2), "background-color": colour(rgb("#94B2CC", 0.35)), **PASSIVE}),
            group(f"{ident}-thumb", {"position": keyword("absolute"), "left": length(0), "top": length(0), "width": length(knob),
                                     "height": ul(ch)}, [vector(f"{ident}-knob", {**FULL, **PASSIVE}, ring)]),
        ])
        value = label(f"{ident}-value", PLACEHOLDER, (cx + cw + 6, 0, 40, h), BODY, 0.28, TEXT_VALUE, align="left", centre=True)
        children += [track_node, *value]
        decimals = 0 if step == int(step) else (1 if step * 10 == int(step * 10) else 2)
        spec.update(role="slider", states=setting_states(doc, ident, f"{ident}-value"), minimum=low, maximum=high,
                    step=step, decimals=decimals, orientation="horizontal",
                    parts={"track": f"{ident}-track", "fill": f"{ident}-fill", "thumb": f"{ident}-thumb", "value": f"{ident}-value"})
    node = group(ident, {**absolute(origin[0] + x, origin[1] + y, w, h), "opacity": number(1)}, children, control=spec)
    if "enabled" in setting:
        doc.bind(ident, "enabled", setting["enabled"])
        doc.bind(ident, "opacity", {"op": "select", "args": [setting["enabled"], 1, 0.4]})
    return node


