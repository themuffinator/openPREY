def home_document(ident: str, in_game: bool) -> dict:
    """The home screen's navigation, out of game (the title) or in game (the
    pause): the arc of hooks, the bottom bar and the small frames that grow
    from it. It is drawn over the stock menu's portal backdrop and wordmark,
    which guis/mainmenu.gui keeps drawing beneath it; pages it has no frame
    for are the stock menu's own (section 12.5)."""
    doc = Document(ident)
    click = doc.session("soundClick")
    doc.state["page.open"] = {"type": "boolean", "initial": False}
    doc.state["home.released"] = {"type": "boolean", "initial": False}

    def act(name: str, verb: str) -> str:
        """A navigation press: Prey's click, then the session verb."""
        doc.events[name] = [{"op": "action", "action": click}, {"op": "action", "action": doc.session(verb)}]
        return name

    def show(name: str, frame: str) -> str:
        doc.events[name] = [{"op": "action", "action": click}, {"op": "call", "event": f"{frame}Show"}]
        return name

    if in_game:
        # What the session publishes on the pause (idSessionLocal::PublishRetainedPauseState).
        for key in ("pause_level", "pause_detail", "pause_objectives", "pause_shot", "pause_stats", "pause_saved"):
            doc.state[key] = {"type": "string", "initial": ""}
        for key, initial in (("pause_objective_count", 0), ("pause_mission_seconds", -1), ("pause_total_seconds", -1)):
            doc.state[key] = {"type": "number", "initial": initial}
        rows = [
            ("nav_resume", "#str_20555", {"event": act("pickResume", "resume")}),
            ("nav_quitgame", "#str_20556", {"event": show("pickQuitGame", "quitgame")}),
            ("nav_savegame", "#str_20333", {"event": act("pickSaveGame", "saveGame")}),
            ("nav_loadgame", "#str_20127", {"event": act("pickLoadGame", "loadGame")}),
            ("nav_options", "#str_20208", {"event": act("pickOptions", "settings")}),
            ("nav_exit", "#str_20554", {"event": show("pickExit", "exit")}),
        ]
        links = [("link_credits", "#str_20017", (170, 4, 140, 25), act("pickCredits", "credits"))]
        frames = [
            confirm_frame(doc, "quitgame", "#str_20332", heading=None, prompt_ty=65, yes_action="quitToMenu",
                          origin="nav_quitgame"),
            confirm_frame(doc, "exit", "#str_20554", heading="#str_20123", prompt_ty=75, yes_action="quit",
                          origin="nav_exit"),
        ]
        first = "nav_resume"
        doc.events["onBack"] = [{"op": "action", "action": "resume"}]
    else:
        # What the session publishes on the title (Session_PublishRetainedTitleState).
        doc.state["menu_continue"] = {"type": "boolean", "initial": False}
        for key in ("menu_continue_title", "menu_continue_detail", "menu_continue_shot"):
            doc.state[key] = {"type": "string", "initial": ""}
        rows = [
            ("nav_resume", "#str_20555", {"event": act("pickResume", "continue")}),
            ("nav_newgame", "#str_20553", {"event": show("pickNewGame", "newgame")}),
            ("nav_loadgame", "#str_20127", {"event": act("pickLoadGame", "loadGame")}),
            ("nav_multiprey", "#str_20135", {"event": act("pickMultiPrey", "multiplayer")}),
            ("nav_options", "#str_20208", {"event": act("pickOptions", "settings")}),
            ("nav_exit", "#str_20554", {"event": show("pickExit", "exit")}),
        ]
        links = [
            ("link_updates", "#str_20343", (28, 4, 142, 25), act("pickUpdates", "updates")),
            ("link_credits", "#str_20017", (170, 4, 140, 25), act("pickCredits", "credits")),
            ("link_mods", "#str_20133", (310, 4, 100, 25), act("pickMods", "mods")),
        ]
        frames = [
            new_game_frame(doc, "nav_newgame"),
            mods_frame(doc, "link_mods"),
            confirm_frame(doc, "exit", "#str_20554", heading="#str_20123", prompt_ty=75, yes_action="quit",
                          origin="nav_exit"),
        ]
        first = "nav_newgame"
        doc.events["onBack"] = [{"op": "call", "event": "pickExit"}]
    for key in ("pointer_x", "pointer_y"):
        doc.state[key] = {"type": "number", "initial": 0}

    # Focus steps down the arc and wraps through the bottom bar.
    nav_ids, link_ids = [row[0] for row in rows], [item[0] for item in links]
    entries = []
    for index, (name, key, how) in enumerate(rows):
        navigation = {"up": nav_ids[index - 1] if index else link_ids[0],
                      "down": nav_ids[index + 1] if index + 1 < len(rows) else link_ids[0],
                      "right": link_ids[0]}
        entries.append(nav_entry(doc, name, key, index, scale=0.40 if name == "nav_exit" else 0.39,
                                 navigation=navigation, **how))
    bottom_links = []
    for index, (name, key, box, event) in enumerate(links):
        navigation = {"up": nav_ids[-1], "down": nav_ids[0],
                      "left": link_ids[index - 1] if index else nav_ids[-1],
                      "right": link_ids[(index + 1) % len(links)]}
        bottom_links.append(link(doc, name, key, box, event=event, navigation=navigation))
    if not in_game:
        # Resume Game shows while a save exists, as the stock entry does.
        entries[0]["properties"]["display"] = keyword("none")
        doc.bind("nav_resume", "display", {"op": "select", "args": [{"state": "menu_continue"}, "block", "none"]})
        focus_first = {"op": "if", "condition": {"state": "menu_continue"},
                       "then": [{"op": "focus", "control": "nav_resume"}],
                       "else": [{"op": "focus", "control": first}]}
    else:
        focus_first = {"op": "focus", "control": first}

    bx, by, bw, bh = BOTTOM_BAR
    bottom = group("bottom", absolute(bx, by, bw, bh), [*frame_parts(doc, "bottom", 0.5, 7, upper=False), *bottom_links])
    # The navigation and the bottom bar hide the moment a frame starts to grow
    # and show again when it is back in the bar (section 8).
    home = group("home", {**absolute(0, 0, CANVAS_W, CANVAS_H), "opacity": number(1), "display": keyword("block")},
                 [arc(), *entries, bottom])
    doc.bind("home", "display", {"op": "select", "args": [
        {"op": "||", "args": [{"state": "page.open"}, {"state": "home.released"}]}, "none", "block"]})
    # The stock menu shows its navigation at once as the backdrop fades in
    # over 100 ms; the home arrives with that fade.
    doc.timeline("open", OPEN_FADE_MS, [track("home", "opacity", [(0, number(0)), (1, number(0)), (OPEN_FADE_MS, number(1))])])
    doc.events["open"] = [
        {"op": "setState", "values": {"home.released": False}},
        {"op": "playTimeline", "timeline": "open"},
        focus_first,
    ]
    doc.events["returnHome"] = [{"op": "call", "event": "open"}]
    # Returning to the game closes the pause at once: nothing of it stays
    # over the running game while the session releases the screen.
    doc.events["release"] = [{"op": "setState", "values": {"home.released": True}}]
    # A retained page (Load Game, Save Game) grows from the bottom bar's place
    # as the home hands off to it, so the navigation and the bar hide at once,
    # as they do for a frame. The session names the request first; Prey's
    # pages carry their own titles, so that changes nothing.
    doc.events["depart"] = [{"op": "setState", "values": {"home.released": True}}]
    for request in ("loadGame", "saveGame", "restartLevel", "credits", "multiplayer", "settings"):
        doc.events[f"carry_{request}"] = [{"op": "setState", "values": {"home.released": True}}]

    # The stock 4:3 canvas, centred: the navigation stays in its leading half
    # and the frames on the central axis at every aspect (section 3).
    stage = group("stage", {"position": keyword("absolute"), "top": length(0), "left": length(50, "%"),
                            "margin-left": length(-CANVAS_W * U / 2), "width": ul(CANVAS_W), "height": ul(CANVAS_H)},
                  [home, *frames])
    root = group("screen", {**FULL, "font-family": font(BODY), "font-size": length(EM * 0.33 * U),
                            "color": colour(TEXT_LABEL)}, [stage])
    return doc.build(root)


