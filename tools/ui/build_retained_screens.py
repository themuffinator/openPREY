# Section 4 of the visual specification. Colours are sRGB with separate alpha.

def rgb(code: str, alpha: float = 1.0) -> list[float]:
    code = code.lstrip("#")
    return [round(int(code[i:i + 2], 16) / 255, 4) for i in (0, 2, 4)] + [alpha]


