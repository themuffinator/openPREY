def video_dirty() -> dict:
    """Whether a setting that takes a video restart differs from what is in
    effect: the condition Apply Changes is lit by."""
    terms = [{"op": "!=", "args": [{"state": f"cv.{name}"}, {"state": f"applied.{name}"}]} for name in VIDEO_RESTART]
    terms.append({"op": "!=", "args": [{"state": "cv.com_performancePreset"}, {"state": "applied.com_performancePreset"}]})
    terms.append({"op": "!=", "args": [{"state": "video.fullscreen"}, {"state": "cv.r_fullscreen"}]})
    result = terms[0]
    for term in terms[1:]:
        result = {"op": "||", "args": [result, term]}
    return result


def page_row(doc: Document, row: dict, origin, tag: str) -> tuple[dict, str]:
    """One stock row as its retained node and the control that takes the
    focus there: a setting row, a size row, the Detect box, or a page's
    Apply Changes button, which is lit while a restart is owed."""
    if row["kind"] == "size":
        return size_row(doc, f"size_{row['fields'][0]['cvar'].lower()}", row, origin)
    if row["kind"] == "detect":
        return detect_box(doc, row, origin)
    if row["kind"] == "apply":
        x, y, w, h = row["rect"]
        ident = f"apply_{tag}"
        doc.events[f"{ident}Pick"] = [{"op": "action", "action": doc.session("soundClick")},
                                      {"op": "action", "action": doc.session("videoApply")}]
        return button(doc, ident, row["label"], (origin[0] + x, origin[1] + y, w, h), event=f"{ident}Pick", scale=0.33,
                      enabled=video_dirty()), ident
    if row["kind"] == "bind":
        node = bind_row(doc, row, origin)
        return node, node["id"]
    node = setting_row(doc, f"opt_{row['cvar'].lower()}", row, origin)
    return node, node["id"]


