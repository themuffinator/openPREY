def _cubic(p0, p1, p2, p3, t: float) -> tuple[float, float]:
    m = 1 - t
    return tuple(m ** 3 * a + 3 * m * m * t * b + 3 * m * t * t * c + t ** 3 * d for a, b, c, d in zip(p0, p1, p2, p3))


def arc_points(count: int) -> list[tuple[float, float]]:
    """`count` points at equal distances along the arc, ends excluded."""
    numbers = [float(v) for v in re.findall(r"-?\d*\.?\d+", ARC_D)]
    pairs = list(zip(numbers[0::2], numbers[1::2]))
    samples = []
    for index in range(0, len(pairs) - 1, 3):
        segment = pairs[index:index + 4]
        samples += [_cubic(*segment, step / 200) for step in range(200 if index + 4 < len(pairs) else 201)]
    lengths = [0.0]
    for a, b in zip(samples, samples[1:]):
        lengths.append(lengths[-1] + math.dist(a, b))
    result, cursor = [], 0
    for step in range(1, count + 1):
        want = lengths[-1] * step / (count + 1)
        while lengths[cursor + 1] < want:
            cursor += 1
        span = lengths[cursor + 1] - lengths[cursor]
        f = (want - lengths[cursor]) / span if span else 0
        a, b = samples[cursor], samples[cursor + 1]
        result.append((a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f))
    return result


def arc() -> dict:
    """The silver-blue arc with its rivets (curve_ig): a shaded edge, the
    rail, a highlight, and 25 rivets along the inner edge, every fourth one a
    socket."""
    paths = [
        svg("edge", ARC_D, stroke=stroke(solid(rgb("#1E2632")), 5.4 * U, cap="butt", join="round")),
        svg("rail", ARC_D, stroke=stroke(solid(rgb("#93ACC4")), 2.6 * U, cap="round", join="round")),
        svg("light", ARC_LIGHT_D, stroke=stroke(solid(rgb("#C8DAEA", 0.5)), 0.7 * U, join="round")),
    ]
    for index, (x, y) in enumerate(arc_points(25), start=1):
        if index % 4 == 0:
            paths.append(svg(f"socket{index}", ellipse_d(x + 1.9, y, 2.1, 2.1), fill=solid(rgb("#2A323D")),
                             stroke=stroke(solid(rgb("#93ACC4")), 0.9 * U)))
        else:
            paths.append(svg(f"rivet{index}", ellipse_d(x + 1.9, y, 1.1, 1.1), fill=solid(rgb("#93ACC4"))))
    return vector("nav-arc", {**absolute(0, 0, CANVAS_W, CANVAS_H), "opacity": number(0.85), **PASSIVE}, paths)


