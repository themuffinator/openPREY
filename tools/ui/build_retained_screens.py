# The stock credits are 169 lines, two banners and three pictures on a sheet
# 5300 u tall that rises through a 400 u window in 130 s. Their places, sizes
# and string keys are read from the stock script, which openPREY carries
# unchanged, so the retained page follows it line for line.

CREDITS_CONTENT = ROOT / "content" / "basepr" / "pak0" / "guis" / "mainmenu" / "mainmenu_creditcontent.guifragment"
CREDITS_DEFINES = ROOT / "content" / "basepr" / "pak0" / "guis" / "mainmenu" / "mainmenu_creditdefines.guifragment"
CREDITS_SHEET = 5300                 # u: the sheet's height (CREDITS_VPAGE_SRCRECT)
CREDITS_WINDOW = (0, 31, 620, 400)   # VirtualPageClipper, in the page frame
CREDITS_ROLL_AT, CREDITS_ROLL_MS = 2700, 130000   # the sheet starts to rise, and for how long
CREDITS_ARM_AT = 2800                # credits start to appear (CreditLine1::onCallEnable)
# A credit appears when its window has risen to canvas y 350
# (idWindow::UpdateRetailCreditActivation); the page frame is at y 10.
CREDITS_APPEAR_Y = 350 - FULL_FRAME[1] - CREDITS_WINDOW[1]
CREDIT_FLY_FROM, CREDIT_FLY_MS = 1000, 500   # a title flies in from x 1000 to its place
CREDIT_SCALE = 0.35                  # a window's default textscale
CREDIT_TINTS = {"HEADING": rgb("#CCDEFA"), "TITLE": [0.82, 0.89, 0.99, 1], "NAME": [0.6, 0.68, 0.78, 0.88]}
# The page's head: (fade starts at ms, final opacity or tint), from Credits_AnimIn.
CREDIT_BANNERS = {"Logo": (700, 0.9), "Title1": (1700, [0.8, 0.87, 0.98, 1]), "HHead": (3500, 1.0),
                  "Title2": (28000, [1, 1, 1, 1]), "ThreeDR": (29000, 1.0)}


def stock_credits() -> list[dict]:
    """The stock credits' windows in script order: name, kind (HEADING, TITLE
    or NAME for a credit; BANNER or PICTURE for the head's five), rect, and
    string key, textscale or picture."""
    defines: dict[str, str] = {}
    for path in (CREDITS_DEFINES, CREDITS_CONTENT):
        continued = False
        for line in path.read_text(encoding="latin-1").splitlines():
            carries = line.rstrip().endswith("\\")
            found = None if continued else re.match(r"\s*#define\s+(\w+)\s+(.*?)\s*(?://.*)?$", line)
            continued = carries
            if found and not carries:      # a one-line value; the window definitions run over many
                defines[found.group(1)] = found.group(2)
    defines["CREDIT_TITLE_XVALUE"] = defines["CREDIT_FINALX"].strip('"')   # a title's place once it has flown in

    def numbers(expression: str) -> list[float]:
        for _ in range(32):                # each section's place is defined from the one before it
            expanded = re.sub(r"[A-Za-z_]\w*", lambda m: defines.get(m.group(0), m.group(0)), expression)
            if expanded == expression:
                break
            expression = expanded
        if not re.fullmatch(r"[\d\s.,+\-*/()]+", expression):
            raise SystemExit(f"credits: cannot evaluate rect {expression!r}")
        return [float(eval(part, {"__builtins__": {}})) for part in expression.split(",")]

    source = re.sub(r"//[^\n]*", "", CREDITS_CONTENT.read_text(encoding="latin-1"))
    items = []
    for found in re.finditer(r"(creditDef|windowDef)\s+(\w+)\s*\{([^{}]*)\}", source):
        name, body = found.group(2), found.group(3)
        rect = re.search(r"^\s*rect\s+(.+?)\s*$", body, re.M)
        key = re.search(r'^\s*text\s+"(#str_\d+)"', body, re.M)
        back = re.search(r'^\s*background\s+"([^"]+)"', body, re.M)
        scale = re.search(r"^\s*textscale\s+([\d.]+)", body, re.M)
        kind = re.search(r"CREDIT_DEFINITION_(\w+)", body)
        item = {"name": name, "rect": tuple(numbers(rect.group(1))), "scale": float(scale.group(1)) if scale else CREDIT_SCALE}
        if kind:
            item.update(kind=kind.group(1), key=key.group(1))
        elif name in CREDIT_BANNERS and key:
            item.update(kind="BANNER", key=key.group(1))
        elif name in CREDIT_BANNERS and back:
            item.update(kind="PICTURE", picture=re.sub(r"\.tga$", "", back.group(1)))
        else:
            raise SystemExit(f"credits: unexpected window {name!r}")
        items.append(item)
    return items


def credits_document() -> dict:
    """Credits: the stock sheet rising through the page. The wordmark, the
    two banners and the studio marks fade in at the stock times; each credit
    appears as it rises to canvas y 350, headings and names in place and
    titles flying in from the trailing side over 500 ms. The sheet takes
    130 s and then starts again."""
    doc = Document("openprey.credits")
    total = CREDITS_ROLL_AT + CREDITS_ROLL_MS
    tracks = [track("credits-sheet", "top", [(0, ul(0)), (1, ul(0)), (CREDITS_ROLL_AT, ul(0)), (total, ul(-CREDITS_SHEET))])]

    def fade_in(node: str, at: int, over: int, to: float) -> None:
        tracks.append(track(node, "opacity", [(0, number(0)), (1, number(0)), (at, number(0)), (at + over, number(to))]))
    sheet = []
    for index, item in enumerate(stock_credits()):
        ident, (x, y, w, h) = f"credit-{index}", item["rect"]
        if item["kind"] == "PICTURE":
            at, level = CREDIT_BANNERS[item["name"]]
            sheet.append(picture(ident, item["picture"], {**absolute(x, y, w, h), "opacity": number(0), **PASSIVE}))
            fade_in(ident, at, 1000, level)
        elif item["kind"] == "BANNER":
            at, tint = CREDIT_BANNERS[item["name"]]
            sheet += label(ident, item["key"], (x, y, w, h), BODY, item["scale"], tint, opacity=number(0))
            fade_in(ident, at, 1000, 1)
        else:
            # The sheet has risen (y - CREDITS_APPEAR_Y) u when this credit appears.
            at = max(CREDITS_ARM_AT, round(CREDITS_ROLL_AT + max(0.0, y - CREDITS_APPEAR_Y) * CREDITS_ROLL_MS / CREDITS_SHEET))
            flies = item["kind"] == "TITLE"
            more = {"transform": transform(CREDIT_FLY_FROM - x)} if flies else {}
            sheet += label(ident, item["key"], (x, y, w, h), BODY, item["scale"], CREDIT_TINTS[item["kind"]], ty=-3,
                           opacity=number(0), **more)
            fade_in(ident, at, 1, 1)
            if flies:
                tracks.append(track(ident, "transform", [
                    (0, transform(CREDIT_FLY_FROM - x)), (1, transform(CREDIT_FLY_FROM - x)),
                    (at, transform(CREDIT_FLY_FROM - x), EASE_IN_OUT), (at + CREDIT_FLY_MS, transform())]))
    # The roll is the page's content, so it keeps its timing under reduced motion.
    doc.timeline("creditsRoll", total, tracks, iterations=0, essential=True)
    window = group("credits-window", {**absolute(*CREDITS_WINDOW), "overflow": keyword("hidden"), **PASSIVE}, [
        group("credits-sheet", {**absolute(0, 0, CREDITS_WINDOW[2], CREDITS_SHEET), **PASSIVE}, sheet)])
    page = full_page(doc, "#str_20017", [window], "creditsBack", [{"op": "focus", "control": "page_back"}])
    doc.events["onActivate"].append({"op": "playTimeline", "timeline": "creditsRoll"})
    return page_document(doc, page, [])


