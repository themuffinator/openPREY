def size_row(doc: Document, ident: str, row: dict, origin) -> tuple[dict, str]:
    """Window Size and Custom Resolution: two number fields either side of an
    "x", centred in the value column, as openPREY's stock row lays them out
    (section 12.1)."""
    place, children = plain_row(ident, row, origin)
    fields = []
    for field in row["fields"]:
        name = OPTION_SETTINGS[field["cvar"].lower()][0]
        low = 240 if name.endswith("Height") else 320
        fields.append(number_field(doc, f"opt_{field['cvar'].lower()}", row["label"], field["cvar"], field["rect"], low, 16384))
    (ax, ay, aw, ah), (bx2, _, _, _) = row["fields"][0]["rect"], row["fields"][1]["rect"]
    mid_x, mid_y = (ax + aw + bx2) / 2, ay + ah / 2
    cross = vector(f"{ident}-by", {**absolute(mid_x - 3, mid_y - 3, 6, 6), **PASSIVE}, [
        svg("a", "M0.5 0.5L5.5 5.5", stroke=stroke(solid(TEXT_VALUE), 1 * U)),
        svg("b", "M5.5 0.5L0.5 5.5", stroke=stroke(solid(TEXT_VALUE), 1 * U))])
    return group(ident, absolute(*place["box"]), [*children, cross, *fields]), fields[0]["id"]


