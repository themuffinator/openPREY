def encode(value, depth: int = 0) -> str:
    """Structured JSON with every small object or array on one line, so the
    generated sources stay reviewable."""
    flat = json.dumps(value, ensure_ascii=False)
    if len(flat) <= 110 or not isinstance(value, (dict, list)) or not value:
        return flat
    pad, inner = " " * depth, " " * (depth + 1)
    if isinstance(value, dict):
        items = [f"{inner}{json.dumps(key, ensure_ascii=False)}: {encode(item, depth + 1)}" for key, item in value.items()]
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    return "[\n" + ",\n".join(f"{inner}{encode(item, depth + 1)}" for item in value) + "\n" + pad + "]"


def render(document: dict) -> str:
    return (HEADER + encode(document) + "\n").replace("\r\n", "\n").replace("\n", "\r\n")


def check_ids(name: str, document: dict) -> None:
    """Node IDs are unique within a document, every timeline, binding and
    focus target names a node that exists, and a bound style property has a
    base value on its node, which the loader requires."""
    seen: dict[str, dict] = {}

    def walk(node: dict) -> None:
        if node["id"] in seen:
            raise SystemExit(f"{name}: duplicate node id {node['id']!r}")
        seen[node["id"]] = node
        for child in node.get("children", ()):
            walk(child)
    walk(document["root"])
    for binding in document.get("bindings", ()):
        node = seen.get(binding["node"])
        if node is not None and binding["property"] != "enabled" and binding["property"] not in node["properties"]:
            raise SystemExit(f"{name}: binding {binding['id']!r} has no base value for {binding['property']!r}")
    for timeline in document["timelines"]:
        for item in timeline["tracks"]:
            if item["node"] not in seen:
                raise SystemExit(f"{name}: timeline {timeline['id']!r} targets missing node {item['node']!r}")
    for binding in document.get("bindings", ()):
        if binding["node"] not in seen:
            raise SystemExit(f"{name}: binding {binding['id']!r} targets missing node {binding['node']!r}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale documents instead of writing them")
    args = parser.parse_args()
    stale = []
    for name, build in DOCUMENTS.items():
        document = build()
        check_ids(name, document)
        rendered = render(document)
        path = OUT / name
        current = path.read_bytes().decode("utf-8").replace("\r\n", "\n") if path.exists() else None
        if current == rendered.replace("\r\n", "\n"):
            continue
        if args.check:
            stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(rendered.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT).as_posix()} ({len(rendered) // 1024} KB)")
    if stale:
        print("stale retained documents: " + ", ".join(stale) + "; run tools/ui/build_retained_screens.py")
        return 1
    return 0


