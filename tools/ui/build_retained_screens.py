    left, top = bx - 6, by - 4
    bar_box = {**absolute(bx - left, by - top, bar_len, BAR_H), **PASSIVE}
    bars = group(f"{ident}-bars", {**absolute(0, 0, 214, NAV_PITCH), "transform": transform(), **PASSIVE}, [
        vector(f"{ident}-bar", {**bar_box, "opacity": number(0.6)}, hook_bar(f"{ident}-bar", bar_len, ARC_BAR)),
        vector(f"{ident}-rim", {**bar_box, "opacity": number(0)}, hook_bar(f"{ident}-rim", bar_len, RAIL, weight=1.5)),
    ])
    # The stock label box sits 8 u above its bar and is 25 u tall.
    text_nodes = label(f"{ident}-label", key, (lx - left, by - 8 - top, 300, 25), DISPLAY, scale, TEXT_NAV,
                       align="left", transform=transform())

    def lit(slide: bool, bar_on: float, rim_on: float, tint: list[float]) -> list:
        return [(f"{ident}-bars", "transform", transform(bar_dx if slide else 0)),
                (f"{ident}-bar", "opacity", number(bar_on)), (f"{ident}-rim", "opacity", number(rim_on)),
                (f"{ident}-label", "transform", transform(label_dx if slide else 0)),
                (f"{ident}-label", "color", colour(tint))]
    ids = doc.states(ident, {
        "default": lit(False, 0.6, 0, TEXT_NAV), "hover": lit(True, 1, 0, TEXT_NAV_HOVER),
        "focus": lit(True, 1, 1, TEXT_NAV_HOVER), "pressed": lit(True, 1, 0, TEXT_HOVER),
        "disabled": lit(False, 0.3, 0, rgb("#B3CCE6", 0.3)),
    })
    return group(ident, absolute(left, top, 214, NAV_PITCH), [bars, *text_nodes],
                 control=control(key, ids, action=action, event=event, **more))


