def video_dirty() -> dict:
    """Whether a setting that takes a video restart differs from what is in
    effect: the condition Apply Changes is lit by."""
    terms = [{"op": "!=", "args": [{"state": f"cv.{name}"}, {"state": f"applied.{name}"}]} for name in VIDEO_RESTART]
    terms.append({"op": "!=", "args": [{"state": "cv.com_performancePreset"}, {"state": "applied.com_performancePreset"}]})
    terms.append({"op": "!=", "args": [{"state": "video.fullscreen"}, {"state": "cv.r_fullscreen"}]})
    result = terms[0]
    for term in terms[1:]:
        result = {"op": "||", "args": [result, term]}
    return result


def page_row(doc: Document, row: dict, origin, tag: str) -> tuple[dict, str]:
    """One stock row as its retained node and the control that takes the
    focus there: a setting row, a size row, the Detect box, or a page's
    Apply Changes button, which is lit while a restart is owed."""
    if row["kind"] == "size":
        return size_row(doc, f"size_{row['fields'][0]['cvar'].lower()}", row, origin)
    if row["kind"] == "detect":
        return detect_box(doc, row, origin)
    if row["kind"] == "apply":
        x, y, w, h = row["rect"]
        ident = f"apply_{tag}"
        doc.events[f"{ident}Pick"] = [{"op": "action", "action": doc.session("soundClick")},
                                      {"op": "action", "action": doc.session("videoApply")}]
        return button(doc, ident, row["label"], (origin[0] + x, origin[1] + y, w, h), event=f"{ident}Pick", scale=0.33,
                      enabled=video_dirty()), ident
    node = setting_row(doc, f"opt_{row['cvar'].lower()}", row, origin)
    return node, node["id"]


def tab_face(ident: str, box, d: str, paint: dict, tint: list[float], key: str, scale: float, *, rim_d: str | None = None,
             rim_tint: list[float] | None = None, ty: float | None = None) -> dict:
    """One state of a tab: its plate, its rim along the free edges when it
    is the active one, and its label."""
    _, _, w, h = box
    paths = [svg("plate", d, fill=paint)]
    if rim_d:
        paths.append(svg("rim", rim_d, stroke=stroke(solid(rim_tint), 1 * U, join="round")))
    text_nodes = label(f"{ident}-label", key, (0, 0, w, h), BODY, scale, tint, **({"centre": True} if ty is None else {"ty": ty}))
    return group(ident, {**absolute(0, 0, w, h), **PASSIVE}, [vector(f"{ident}-plate", {**FULL, **PASSIVE}, paths), *text_nodes])


def tab_button(doc: Document, ident: str, box, key: str, faces: tuple, event: str, active) -> dict:
    """A tab (section 6). Idle it is a separate plate with prey.text.tab; the
    pointer or focus turns its label prey.text.tabHover, and focus adds a
    hairline in prey.rail. Active it is the page's own surface with a white
    label. `active` is True, False or a condition over state; `faces` are the
    idle and active tab_face builders' results."""
    x, y, w, h = box
    idle, lit_face = faces
    rim = vector(f"{ident}-focus", {**absolute(6, h - 3, w - 12, 2), "opacity": number(0), **PASSIVE}, [
        svg("rail", f"M0 1H{w - 12}", stroke=stroke(solid(RAIL), 1 * U))])
    def lit(tint: list[float], rim_on: float) -> list:
        return [(f"{idle['id']}-label", "color", colour(tint)), (f"{ident}-focus", "opacity", number(rim_on))]
    ids = doc.states(ident, {"default": lit(TAB_TEXT, 0), "hover": lit(TAB_TEXT_HOVER, 0), "focus": lit(TAB_TEXT_HOVER, 1),
                             "pressed": lit(TEXT_HOVER, 0), "disabled": lit(rgb("#B5C9E3", 0.3), 0)}, enter=1, leave=1)
    if active is True:
        idle["properties"]["display"] = keyword("none")
    elif active is False:
        lit_face["properties"]["display"] = keyword("none")
    else:
        shown_when(doc, lit_face, active)
        shown_when(doc, idle, {"op": "!", "args": [active]})
    return group(ident, absolute(x, y, w, h), [idle, lit_face, rim], control=control(key, ids, event=event))


def line(ident: str, box) -> dict:
    """A 1 u run of the tab page's outline, in prey.separator."""
    return box_fill(ident, box, SEPARATOR)


