def bound(doc: Document, nodes: list[dict], value) -> list[dict]:
    """Text the session supplies: every text node in `nodes` shows `value`,
    a string state or an expression over state."""
    for node in nodes:
        doc.bind(node["id"], "text", value if isinstance(value, dict) else {"state": value})
    return nodes


def shown_when(doc: Document, node: dict, condition, display: str = "block") -> dict:
    node["properties"]["display"] = keyword("none")
    doc.bind(node["id"], "display", {"op": "select", "args": [condition, display, "none"]})
    return node


def box_fill(ident: str, box, tint: list[float], *, border: list[float] | None = None, **more) -> dict:
    """A flat cell: the stock windows' backcolor with a 1 u border."""
    props = {**absolute(*box), "background-color": colour(tint), **PASSIVE, **more}
    if border:
        props.update({"border-width": ul(1), "border-color": colour(border), "box-sizing": keyword("border-box")})
    return group(ident, props)


def picture_frame(ident: str, box) -> dict:
    """The picture frame (pictureframe_corner, _left, _strip): a rounded
    outline in prey.frame.picture, 1.4 u wide, with no fill."""
    x, y, w, h = box
    r, k = 3.5 * U, 3.5 * U * 0.5523
    right, foot = far(), far()
    commands = [
        {"id": "p0", "op": "move", "points": [[r, 0]]},
        {"id": "p1", "op": "line", "points": [[far(r), 0]]},
        {"id": "p2", "op": "cubic", "points": [[far(r - k), 0], [right, r - k], [right, r]]},
        {"id": "p3", "op": "line", "points": [[right, far(r)]]},
        {"id": "p4", "op": "cubic", "points": [[right, far(r - k)], [far(r - k), foot], [far(r), foot]]},
        {"id": "p5", "op": "line", "points": [[r, foot]]},
        {"id": "p6", "op": "cubic", "points": [[r - k, foot], [0, far(r - k)], [0, far(r)]]},
        {"id": "p7", "op": "line", "points": [[0, r]]},
        {"id": "p8", "op": "cubic", "points": [[0, r - k], [r - k, 0], [r, 0]]},
        {"id": "close", "op": "close"},
    ]
    return vector(ident, {**absolute(x, y, w, h), **PASSIVE}, [
        {"id": "frame", "commands": commands, "stroke": stroke(solid(PICTURE_FRAME), 1.4 * U, join="round")}])


def navigate(nodes: list[dict], ident: str, **directions: str) -> None:
    """Author `directions` on the control `ident`, found among `nodes` and
    their subtrees. A control that names itself is an edge; a target that is
    hidden falls back to the nearest control that way."""
    pending = list(nodes)
    while pending:
        node = pending.pop()
        if node.get("id") == ident and "control" in node:
            node["control"].setdefault("navigation", {}).update(directions)
            return
        pending += node.get("children", [])
    raise SystemExit(f"navigate: no control '{ident}'")


def full_page(doc: Document, title_key: str, contents: list[dict], back: str, focus: list[dict], *, alpha: float = 0.7,
              back_scale: float = 0.40, foot: tuple = (), back_navigation: dict | None = None) -> dict:
    """A full-screen page's frame (section 8). As the session presents the
    page it widens from the bottom bar to the full-width bar over 200 ms and
    then rises to 620x460 u at 10,10 over 500 ms with the even ease-in-out;
    on the session's "pageLeave" it shrinks the same way back, and the home
    takes the screen when it is in the bar (idSessionLocal::LeaveRetainedPage).
    Its contents keep their places in the frame and are uncovered as it
    grows. `back` is the session verb that leaves the page and `focus` the
    event program that places the focus on arrival."""
    bx, by, bw, bh = BOTTOM_BAR
    fx, fy, fw, fh = FULL_FRAME
    total = WIDEN_MS + GROW_MS
    # A play starts from where the property stands, so each arrival states
    # its start again at 1 ms: the page may have been left at full size.
    doc.timeline("pageEnter", total, [
        track("page", "left", [(0, ul(bx)), (1, ul(bx)), (WIDEN_MS, ul(fx))]),
        track("page", "width", [(0, ul(bw)), (1, ul(bw)), (WIDEN_MS, ul(fw))]),
        track("page", "top", [(0, ul(by)), (1, ul(by)), (WIDEN_MS, ul(by), EASE_IN_OUT), (total, ul(fy))]),
        track("page", "height", [(0, ul(bh)), (1, ul(bh)), (WIDEN_MS, ul(bh), EASE_IN_OUT), (total, ul(fh))]),
        *[track(node, "opacity", [(0, number(0)), (1, number(0)), (WIDEN_MS, number(0)), (WIDEN_MS + 60, number(1))])
          for node in ("page-upper", "page-head")],
    ])
    doc.timeline("pageLeave", total, [
        track("page", "top", [(0, ul(fy), EASE_IN_OUT), (GROW_MS, ul(by))]),
        track("page", "height", [(0, ul(fh), EASE_IN_OUT), (GROW_MS, ul(bh))]),
        track("page", "left", [(0, ul(fx)), (GROW_MS, ul(fx)), (total, ul(bx))]),
        track("page", "width", [(0, ul(fw)), (GROW_MS, ul(fw)), (total, ul(bw))]),
        *[track(node, "opacity", [(0, number(1)), (GROW_MS - 60, number(1)), (GROW_MS, number(0))])
          for node in ("page-upper", "page-head")],
    ])
    doc.session(back)
    doc.events["onActivate"] = [
        {"op": "action", "action": doc.session("soundSlideIn")},
        {"op": "playTimeline", "timeline": "pageEnter"},
        *focus,
    ]
    doc.events["pageLeave"] = [
        {"op": "action", "action": doc.session("soundSlideOut")},
        {"op": "playTimeline", "timeline": "pageLeave"},
    ]
    doc.events["onBack"] = [{"op": "action", "action": back}]
    # `alpha` is the body's (0.50 on the Options page), `back_scale` the bottom
    # action's textscale and `foot` further actions on the bottom title bar.
    parts = frame_parts(doc, "page", alpha, 7)
    for part in parts:
        if part["id"] == "page-upper":
            part["properties"]["opacity"] = number(0)
    # The title bar appears when the vertical growth starts, with the upper
    # claws: a frame no taller than its corners has neither.
    inner = group("page-contents", absolute(0, 0, fw, fh), [
        group("page-head", {**FULL, "opacity": number(0), **PASSIVE}, [
            title_bar("page-title-bar", (32, 8, 556, 24)),
            *label("page-title", title_key, (32, 8, 556, 24), DISPLAY, 0.55, TEXT_NAV, shadow=True, ty=-8)]),
        title_bar("page-foot-bar", (32, 432, 556, 19), inverted=True),
        *contents,
        link(doc, "page_back", RETURN_KEY, (32 + 8, 432, 250, 19), action=back, scale=back_scale, ty=-6,
             **({"navigation": back_navigation} if back_navigation else {})),
        *foot,
    ])
    return group("page", {**absolute(bx, by, bw, bh), "overflow": keyword("hidden")}, [*parts, inner])


