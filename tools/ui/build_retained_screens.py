def script_blocks(text: str) -> tuple[str, list[tuple[str, str, str]]]:
    """A GUI script block's own lines and its child windows as
    (kind, name, body). Event scripts (onAction and the like) are dropped."""
    own, children, index = [], [], 0
    opener = re.compile(r"(\w+Def)\s+(\w+)\s*\{|\{")
    while True:
        found = opener.search(text, index)
        if not found:
            own.append(text[index:])
            break
        depth, end = 1, found.end()
        while depth and end < len(text):
            depth += {"{": 1, "}": -1}.get(text[end], 0)
            end += 1
        if found.group(1):
            own.append(text[index:found.start()])
            children.append((found.group(1), found.group(2), text[found.end():end - 1]))
        else:   # an event script: drop it and the handler's name before it
            own.append(re.sub(r"[^\n]*$", "", text[index:found.start()]))
        index = end
    return "".join(own), children


def script_value(own: str, key: str) -> str | None:
    found = re.search(r"^\s*" + key + r'\s+"?([^"\n]*?)"?\s*$', own, re.M | re.I)
    return found.group(1) if found else None


def script_rect(own: str) -> tuple:
    return tuple(float(part) for part in script_value(own, "rect").split(","))


def stock_rows(children: list, offset=(0.0, 0.0), section: str | None = None) -> tuple[list[dict], list[dict]]:
    """The headings and setting rows among a stock page's child windows, at
    their places on the page. A window of sub-options (the Audio tab's two)
    contributes its own under its name as their `section`."""
    headings, rows = [], []
    for kind, name, body in children:
        own, parts = script_blocks(body)
        setting = next(((k, b) for k, _, b in parts if k in ("choiceDef", "sliderDef")), None)
        edits = [script_blocks(b)[0] for k, _, b in parts if k == "editDef"]
        x, y, w, h = script_rect(own)
        place = (x + offset[0], y + offset[1], w, h)
        if setting is None and edits:
            # A size: two number fields either side of an "x".
            caption = script_blocks(next(b for k, _, b in parts if k == "windowDef" and script_value(script_blocks(b)[0], "text")))[0]
            rows.append({"kind": "size", "rect": place, "label": script_value(caption, "text"), "label_rect": script_rect(caption),
                         "label_ty": float(script_value(caption, "textaligny") or 0), "section": section, "cvar": None,
                         "fields": [{"cvar": script_value(edit, "cvar"), "rect": script_rect(edit)} for edit in edits]})
            continue
        if name.endswith("_ApplyChanges"):
            rows.append({"kind": "apply", "rect": place, "label": script_value(own, "text"), "section": section, "cvar": None})
            continue
        if name == "OVN_Autodetect":
            # The Detect box: a caption and the button that loads the recommended preset.
            caption = script_blocks(next(b for k, _, b in parts if k == "windowDef"))[0]
            press = script_blocks(next(b for k, _, b in parts if k == "buttonDef"))[0]
            rows.append({"kind": "detect", "rect": place, "label": script_value(caption, "text"), "label_rect": script_rect(caption),
                         "label_ty": float(script_value(caption, "textaligny") or 0), "button": script_value(press, "text"),
                         "button_rect": script_rect(press), "section": section, "cvar": None})
            continue
        if setting is None:
            if "text_titlebar" in own:
                x, y, w, h = script_rect(own)
                headings.append({"rect": (x + offset[0], y + offset[1], w, h), "key": script_value(own, "text"), "section": section})
            elif kind == "windowDef" and name.startswith("OA_Suboptions_"):
                x, y, _, _ = script_rect(own)
                more_headings, more_rows = stock_rows(parts, (offset[0] + x, offset[1] + y), name.rsplit("_", 1)[1].lower())
                headings += more_headings
                rows += more_rows
            continue
        caption = script_blocks(next(b for k, _, b in parts if k == "windowDef" and script_value(script_blocks(b)[0], "text")))[0]
        control = script_blocks(setting[1])[0]
        x, y, w, h = script_rect(own)
        row = {"rect": (x + offset[0], y + offset[1], w, h), "label": script_value(caption, "text"),
               "label_rect": script_rect(caption), "label_ty": float(script_value(caption, "textaligny") or 0),
               "control_rect": script_rect(control), "section": section,
               # The resolution row names a GUI variable rather than a CVar.
               "cvar": script_value(control, "cvar") or script_value(control, "gui")}
        if setting[0] == "choiceDef":
            values = script_value(control, "values")
            row.update(kind="choice", choices=script_value(control, "choices"), values=values.split(";") if values else None)
        else:
            row.update(kind="slider", low=float(script_value(control, "low")), high=float(script_value(control, "high")),
                       step=float(script_value(control, "step")))
        rows.append(row)
    return headings, rows


def stock_options(tab: str) -> dict:
    """One top tab of the stock Options page: its label and its pages. A tab
    with side tabs has one page for each, with the side tab's label; Audio
    has a single page with no side tab. Each page gives its place in the tab
    page, its headings and its setting rows."""
    source = re.sub(r"//[^\n]*", "", OPTIONS_SOURCE.read_text(encoding="latin-1"))
    found = re.search(r"tabDef\s+" + tab + r"\s*\{", source)
    depth, end = 1, found.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(source[end], 0)
        end += 1
    own, children = script_blocks(source[found.end():end - 1])
    result = {"key": script_value(own, "text"), "sides": []}
    container = next((body for kind, _, body in children if kind == "tabContainerDef"), None)
    if container is None:
        # One page: a window that holds the page window.
        outer_own, outer_children = script_blocks(next(b for k, _, b in children if k == "windowDef"))
        page_own, page_children = script_blocks(next(b for k, _, b in outer_children if k == "windowDef"))
        ox, oy, _, _ = script_rect(outer_own)
        px, py, pw, ph = script_rect(page_own)
        headings, rows = stock_rows(page_children)
        result["sides"].append({"name": tab, "key": None, "ty": 0.0, "page": (ox + px, oy + py, pw, ph),
                                "headings": headings, "rows": rows})
        return result
    for kind, name, body in script_blocks(container)[1]:
        if kind != "tabDef":
            continue
        side_own, side_children = script_blocks(body)
        tx, ty, _, _ = script_rect(side_own)
        page_own, page_children = script_blocks(next(b for k, _, b in side_children if k == "windowDef"))
        px, py, pw, ph = script_rect(page_own)
        headings, rows = stock_rows(page_children)
        result["sides"].append({"name": name, "key": script_value(side_own, "text"),
                                "ty": float(script_value(side_own, "textaligny") or 0),
                                "page": (tx + px, ty + py, pw, ph), "headings": headings, "rows": rows})
    return result


