def row_setting(doc: Document, row: dict) -> dict:
    """How a stock row's setting is read and changed. Most are settings the
    engine lets a page change directly (OPTION_SETTINGS), read back from the
    CVar. The rest (OPTION_VERBS) the session acts on: the row sends a verb
    with its value, and reads either a CVar or a state the session
    publishes. Returns the control's value state, its action, the value's
    kind and what the row's stock control is overridden with."""
    cvar = row["cvar"].lower()
    if cvar in OPTION_VERBS:
        via = OPTION_VERBS[cvar]
        kind, state = via["kind"], via.get("state") or f"cv.{via['cvar']}"
        declared = {"type": kind, "initial": {"boolean": False, "number": 0}[kind]}
        if "cvar" in via:
            declared["cvar"] = via["cvar"]
        doc.state[state] = declared
        if via.get("local"):     # a value the page keeps until a verb sends it
            doc.actions[via["verb"]] = {"input": kind, "operation": "ui.state.set",
                                        "arguments": {"key": state, "value": {"input": "value"}}}
        else:
            doc.actions[via["verb"]] = {"input": kind, "operation": "session.menuValue",
                                        "arguments": {"command": via["verb"], "value": {"input": "value"}}}
        return {"state": state, "action": via["verb"], "kind": kind, **via}
    name, kind = OPTION_SETTINGS[cvar]
    state, action = f"cv.{name}", f"set.{name}"
    doc.state[state] = {"type": kind, "initial": {"boolean": False, "number": 0, "string": ""}[kind], "cvar": name}
    doc.actions[action] = {"input": kind, "operation": "settings.player.set", "arguments": {"cvar": name, "value": {"input": "value"}}}
    result = {"state": state, "action": action, "kind": kind}
    if cvar in OPTION_ENABLED:
        result["enabled"] = OPTION_ENABLED[cvar]
    return result


def setting_row(doc: Document, ident: str, row: dict, origin) -> dict:
    """A setting row at its stock place (section 6): the graded plate, the
    label centred in the leading half in prey.text.label and the value in
    the trailing half in prey.text.value. A choice shows its current option
    and unfolds its list; a slider is the stock rail with its ring knob, and
    shows its number after it. A row the sound system does not offer is
    drawn at 0.40 and takes no input, as the stock page dims it."""
    x, y, w, h = row["rect"]
    setting = row_setting(doc, row)
    kind = setting["kind"]
    d = row_d(w, h)
    size = {**absolute(0, 0, w, h), **PASSIVE}
