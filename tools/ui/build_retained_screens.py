def small_frame(doc: Document, ident: str, title_key: str, title_scale: float, title_ty: float,
                contents: list[dict], *, focus: str, origin: str) -> dict:
    """A small sub-menu frame that grows out of the bottom bar (section 8):
    from the bar's rectangle to 376x270 u at 180,200 over 500 ms with an even
    ease-in-out, and back. Its contents keep their places in the frame and
    are uncovered as it grows, as the stock windows are. `focus` is the
    control it opens on and `origin` the navigation entry that opened it,
    which takes the focus back when it has closed."""
    bx, by, bw, bh = BOTTOM_BAR
    sx, sy, sw, sh = SMALL_FRAME
    doc.state[f"{ident}.visible"] = {"type": "boolean", "initial": False}
    doc.bind(ident, "display", {"op": "select", "args": [{"state": f"{ident}.visible"}, "block", "none"]})

    def grow(a, b) -> list:
        (ax, ay, aw, ah), (cx, cy, cw, ch) = a, b
        return [track(ident, prop, [(0, ul(start), EASE_IN_OUT), (GROW_MS, ul(end))])
                for prop, start, end in (("left", ax, cx), ("top", ay, cy), ("width", aw, cw), ("height", ah, ch))]
    # The upper claws and the top rail belong to a frame taller than its
    # corners: they arrive as the growth starts and leave as it ends.
    doc.timeline(f"{ident}Enter", GROW_MS, grow(BOTTOM_BAR, SMALL_FRAME) + [
        track(f"{ident}-upper", "opacity", [(0, number(0)), (60, number(1))])])
    doc.timeline(f"{ident}Leave", GROW_MS, grow(SMALL_FRAME, BOTTOM_BAR) + [
        track(f"{ident}-upper", "opacity", [(0, number(1)), (GROW_MS - 60, number(1)), (GROW_MS, number(0))])],
        complete=f"{ident}Hidden")
    doc.events[f"{ident}Show"] = [
        {"op": "action", "action": doc.session("soundSlideInSmall")},
        {"op": "setState", "values": {f"{ident}.visible": True, "page.open": True}},
        {"op": "playTimeline", "timeline": f"{ident}Enter"},
    ]
    doc.events[f"{ident}Hide"] = [
        {"op": "action", "action": doc.session("soundSlideOutSmall")},
        {"op": "playTimeline", "timeline": f"{ident}Leave"},
    ]
    doc.events[f"{ident}Cancel"] = [
        {"op": "action", "action": doc.session("soundCancel")},
        {"op": "call", "event": f"{ident}Hide"},
    ]
    # The navigation reappears when the frame is back in the bar.
    doc.events[f"{ident}Hidden"] = [
        {"op": "setState", "values": {f"{ident}.visible": False, "page.open": False}},
        {"op": "focus", "control": origin},
    ]
    parts = frame_parts(doc, ident, 0.7, 1)
    for part in parts:
        if part["id"] == f"{ident}-upper":
            part["properties"]["opacity"] = number(0)
    top_bar = title_bar(f"{ident}-title-bar", (32, 8, 312, 24))
    title = label(f"{ident}-title", title_key, (32, 8, 312, 24), DISPLAY, title_scale, TEXT_NAV, shadow=True,
                  ty=title_ty)
    foot_bar = title_bar(f"{ident}-foot-bar", (32, 243, 312, 19), inverted=True)
    back = link(doc, f"{ident}_back", RETURN_KEY, (32 + 19, 243, 250, 19), event=f"{ident}Hide", scale=0.40, ty=-6)
    inner = group(f"{ident}-contents", absolute(0, 0, sw, sh), [top_bar, *title, foot_bar, *contents, back])
    return group(ident, {**absolute(bx, by, bw, bh), "overflow": keyword("hidden"), "display": keyword("none")},
                 [*parts, inner], modal={"initialFocus": focus, "back": f"{ident}Hide"})


