#!/usr/bin/env python3
"""Emit the Vulkan native-program table from explicitly reviewed source hashes.

This tool never updates hashes from source files. A changed GLSL implementation
requires review against its native shader before its signature can be admitted.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[2]


def generate(manifest):
    assert manifest['schema'] == 1 and manifest['normalization'] == 'CRLF to LF only'
    lines = ['// Generated by tools/build/vulkan_material_sources.py. Do not edit.',
             '// Hashes identify reviewed sources; source text is not embedded.',
             '#ifndef OPENQ4_VK_MATERIAL_SOURCE_SIGNATURES_H',
             '#define OPENQ4_VK_MATERIAL_SOURCE_SIGNATURES_H',
             'struct vkNativeMaterialSourceSignature_t {',
             '    const char *program;', '    vkGLSLProgramFamily_t family;',
             '    const char *vertexSHA256;', '    const char *fragmentSHA256;', '};',
             'static const vkNativeMaterialSourceSignature_t vkNativeMaterialSources[] = {']
    names = set()
    for entry in manifest['programs']:
        name, family = entry['program'], entry['family']
        assert re.fullmatch(r'(?:glsl/)?[a-z0-9_]+\.(?:glsl|fs)', name) and name not in names
        assert re.fullmatch(r'VK_GLSL_PROGRAM_FAMILY_[A-Z0-9_]+', family)
        names.add(name)
        signatures = entry['sources'] or [dict(vertexSHA256='', fragmentSHA256='')]
        for pair in signatures:
            hashes = [pair['vertexSHA256'], pair['fragmentSHA256']]
            assert all(re.fullmatch(r'[a-f0-9]{64}', value) for value in hashes) or hashes == ['', '']
            lines.append(f'    {{"{name}", {family}, "{hashes[0]}", "{hashes[1]}"}},')
    return '\n'.join(lines + ['};', '#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, default=ROOT / 'src/renderer/Vulkan/material_program_sources.json')
    parser.add_argument('--header', type=Path, default=ROOT / 'src/renderer/Vulkan/vk_MaterialSourceSignatures.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(json.loads(args.manifest.read_text(encoding='utf-8')))
    if args.check:
        if args.header.read_text(encoding='utf-8') != text:
            parser.error('native material source table differs from its reviewed manifest')
    else:
        args.header.write_text(text, encoding='utf-8')
    print('Native material source signature table: ' + ('verified' if args.check else 'generated'))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
